// @ts-check
// Everything Hello Claude writes is generated here, from the interview answers, and nowhere
// else. The wizard page imports this for its live preview; the server imports it to write the
// files. One source: what you see in the preview is byte-for-byte what lands on disk.
//
// Browser-safe on purpose: no Node imports. A "doc" is an array of sections, each
// { id, lines }, and a line is { c: class, t: text } — the page renders that directly and
// docToText() flattens it for disk.

/** @typedef { { c: string, t: string } } Line */
/** @typedef { { id: string, lines: Line[] } } Section */
/** @typedef { Section[] } Doc */

/** The interview's starting answers. Spread into a fresh object before mutating. */
export const DEFAULTS = Object.freeze({
  name:"", role:"", domains:"",
  projDesc:"", langs:"", experience:"comfortable", brandkit:"",
  authority:"options", signoff:"yes",
  tone:"warm", brake:"yes",
  sot:"docs", done:"confirm",
  repos:"single", deploy:"unsure", flow:"branch",
  validate:true, confirmDestructive:true,
  memory:true, docvsmem:true, getToKnow:true,
  daterots:true, path:"",
});

/** @typedef { typeof DEFAULTS } Answers */

function nameOwner(a){ return (a.name.trim() || "The owner"); }
function possessive(a){ const n=a.name.trim(); return n ? n : "the owner"; }

export function genContract(a, opts={}){
  const S=[]; const sec=(id,lines)=>S.push({id,lines});
  const L=(c,t)=>({c,t}); const blank=()=>({c:"blank",t:""});
  const today=opts.today ?? new Date().toISOString().slice(0,10);

  sec("head",[
    L("h1","# How we work — operating contract (binds every session, any model)"),
    blank(),
    L("cmt","> Generated by Hello Claude · "+today+(a.name.trim()?(" · personalized for "+a.name.trim()):"")),
    blank(),
    L("strong","**These rules OVERRIDE default behavior and MUST be followed.**"),
    L("b","They live in the always-loaded project instructions on purpose — so they bind regardless"),
    L("b","of which model is running or whether memory happens to load."),
  ]);

  const pj=[L("h2","## This project")];
  if (a.projDesc.trim()) pj.push(L("li","- What this is: "+a.projDesc.trim()));
  if (a.langs.trim()) pj.push(L("li","- Primary languages / tools: "+a.langs.trim()+" — follow their conventions and idioms."));
  if (a.experience==="new") pj.push(L("li","- Assume limited coding experience — explain the reasoning and teach as you go; don't just hand over code."));
  else if (a.experience==="experienced") pj.push(L("li","- Assume strong coding fluency — be concise and technical; skip the basics."));
  else pj.push(L("li","- Assume comfortable coding experience — explain the non-obvious, skip the basics."));
  if (a.brandkit.trim()) pj.push(L("li","- Brand & design: match the brand kit / guidelines — "+a.brandkit.trim()+". Don't invent brand choices; ask if unsure."));
  sec("project",pj);

  const d=[];
  if (a.authority==="options"){
    d.push(L("h2","## "+nameOwner(a)+" decides. You bring options + a recommendation, then STOP."));
    d.push(L("li","- Do not assume, pick a default, or proceed on anything that lasts — architecture,"));
    d.push(L("li","  schema, data model, vendors, naming, IDs. Lay out options, recommend one, wait for a yes."));
  } else if (a.authority==="default"){
    d.push(L("h2","## Decisions & autonomy"));
    d.push(L("li","- For durable choices, pick a sensible default and tell "+possessive(a)+" what you chose and why."));
  } else {
    d.push(L("h2","## Decisions & autonomy"));
    d.push(L("li","- Move with autonomy on durable choices; surface only what's genuinely hard to reverse."));
  }
  if (a.signoff==="yes") d.push(L("li","- Scope → clear → build. Do not write code or commit to a plan until it's signed off."));
  else d.push(L("li","- Proceed when confident; pause for sign-off only on the big, hard-to-reverse forks."));
  if (a.brake==="yes") d.push(L("li","- Be the brake. Name scope creep and questionable calls; don't just comply."));
  d.push(L("li","- One thread at a time. Finish and confirm the current thing before starting another."));
  sec("decisions",d);

  const st=[L("h2","## Status vs. decisions")];
  if (a.sot==="docs"){
    st.push(L("li","- The committed docs + the code are the source of truth for status. Memory is a mirror,"));
    st.push(L("li","  and it drifts — trust docs and code over memory."));
  } else st.push(L("li","- Ask "+possessive(a)+" for current status; there's no committed record to trust over memory."));
  if (a.done==="confirm") st.push(L("li","- Mark a task done only on explicit confirmation — never on your own assessment."));
  else st.push(L("li","- You may mark work done when it looks complete; confirm if unsure."));
  if (a.memory && a.docvsmem) st.push(L("li","- On a sparked idea, ask \"doc or memory?\" — don't auto-decide its home."));
  sec("status",st);

  if (a.daterots) sec("daterots",[
    L("h2","## Date what rots. Check what you're standing on."),
    L("li","- Date the entries that go stale — decisions, status claims, instructions to future-you."),
    L("li","- ⭐ Record the dependency, not just the date, when an entry rests on something outside"),
    L("li","  your control (a vendor, a platform, an API). Naming it is what warns the next reader."),
  ]);

  const hy=[L("h2","## Build / commit / repo hygiene")];
  hy.push(L("li","- Run git status before committing; review the diff and scan for secrets before every commit."));
  if (a.deploy==="yes"||a.deploy==="unsure") hy.push(L("li","- ⚠ Treat main as LIVE — a push to main reaches real users. Never push untested to main."));
  if (a.flow==="branch"){ const sc=(a.deploy==="yes"||a.deploy==="unsure")?" (production only changes when the owner says so)":""; hy.push(L("li","- Code changes go branch → owner reviews → merge"+sc+".")); }
  else hy.push(L("li","- Direct commits to main are fine for ordinary work."));
  if (a.repos==="multi") hy.push(L("li","- Multiple repos: confirm you're in the right one before any commit or deploy."));
  hy.push(L("li","- Bugs → a BUG-LOG.md (symptom → cause → fix + commit). Ship a QA checklist with each feature."));
  sec("hygiene",hy);

  if (a.validate||a.confirmDestructive){
    const ds=[L("h2","## Never destroy data. Validate before any write.")];
    if (a.validate){
      ds.push(L("b","Most write paths destroy first and validate never — w / > / Out-File / sed -i, and heredocs"));
      ds.push(L("b","piped into an interpreter, all truncate the target at OPEN. Build and encode the full output"));
      ds.push(L("b","before the target is opened; assert it looks right; verify after. A shell \"unexpected EOF\" is"));
      ds.push(L("b","NOT proof nothing ran — verify the file before retrying."));
    }
    if (a.confirmDestructive) ds.push(L("li","- Show genuinely destructive commands (rm -rf, git reset --hard, > over a file, DROP/DELETE) first."));
    sec("safety",ds);
  }

  if (a.authority==="options"||a.signoff==="yes") sec("ask",[
    L("h2","## When in doubt, ASK."),
    L("b","A pause to confirm is never the wrong move; running ahead is."),
  ]);

  if (a.memory && a.getToKnow) sec("getknow",[
    L("h2","## Get to know "+possessive(a)+" (until you do)"),
    L("li","- The private primer has a \"Still learning\" section. While anything in it is blank, you are new"),
    L("li","  here — so at natural pauses (a task just finished, a wait), ask ONE question that would fill a"),
    L("li","  blank. Never a questionnaire; never before the work they came for."),
    L("li","- Ask what a good colleague would want to know in the first week: how they like to be talked to,"),
    L("li","  what humor lands, what wastes their time, the words and shorthand they use, when they're working,"),
    L("li","  how they want to be told they're wrong. Pick the question from what's still blank — don't run a script."),
    L("li","- Write what you learn into the primer the same session. Once nothing is blank, stop asking and"),
    L("li","  just use it. If they say \"stop asking\", stop — and note that."),
    L("li","- If there is no memory dir (another tool, a fresh machine), ask where to keep notes instead of asking nothing."),
  ]);

  if (a.memory) sec("memfoot",[
    blank(),
    L("cmt","> The deeper context — who you are, how you work — lives in the local memory files"),
    L("cmt","> (private, not committed). Read them. But this contract binds even when they are not loaded."),
  ]);

  return S;
}

function toneLine(a){
  return a.tone==="warm" ? "Warm, direct, personable — a colleague, not a servant or a cheerleader."
       : a.tone==="terse" ? "Brief. Short answers, no preamble." : "Clear, professional, straightforward.";
}
function decisionLine(a){
  return a.authority==="options" ? "Bring options + a recommendation, then STOP and wait for a yes."
       : a.authority==="default" ? "Pick a sensible default and say what was picked." : "Use best judgment; surface only the hard-to-reverse.";
}

export function genMemory(a, opts={}){
  const S=[]; const sec=(id,lines)=>S.push({id,lines});
  const L=(c,t)=>({c,t}); const blank=()=>({c:"blank",t:""});
  const today=opts.today ?? new Date().toISOString().slice(0,10);
  const who=[ "**Owner: "+nameOwner(a)+"**" ];
  if (a.role.trim()) who.push(a.role.trim());
  if (a.domains.trim()) who.push("knows deeply: "+a.domains.trim()+" — engage those at peer level");
  sec("head",[
    L("cmt","<!-- PRIVATE local memory for this project. Auto-loaded every session."),
    L("cmt","     Lives OUTSIDE the repo tree — never committed. -->"),
    blank(),
    L("h2","## CORE — read before acting"),
    L("li","- "+who.join(" — ")+"."),
    L("li","- **How we work:** "+toneLine(a)+" "+decisionLine(a)+" Full contract: this repo's CLAUDE.md."),
  ]);
  const pj=[];
  if (a.projDesc.trim()) pj.push(L("li","- **This project:** "+a.projDesc.trim()));
  pj.push(L("li","- **STATUS (updated "+today+"):** just set up with Hello Claude. Nothing started yet — update this line when that changes."));
  sec("project",pj);
  sec("index",[
    blank(),
    L("h2","## Index"),
    L("li","- [Private context primer](PRIVATE-context-primer.md) — who "+possessive(a)+" is, how you work together"+(a.getToKnow?", and what you're still learning.":".")),
  ]);
  return S;
}

export function genPrimer(a, opts={}){
  const S=[]; const sec=(id,lines)=>S.push({id,lines});
  const L=(c,t)=>({c,t}); const blank=()=>({c:"blank",t:""});
  const today=opts.today ?? new Date().toISOString().slice(0,10);
  sec("head",[
    L("h1","# ⛔ PRIVATE — do not commit"),
    blank(),
    L("b","This file lives in the project's local Claude memory dir, outside the repo. It re-associates a fresh"),
    L("b","session with who "+possessive(a)+" is and how you work together. Everything here was either answered at"),
    L("b","setup ("+today+") or learned in conversation — date what you add."),
  ]);
  const who=[blank(), L("h2","## Who "+possessive(a)+" is")];
  if (a.role.trim()) who.push(L("li","- Role: "+a.role.trim()));
  if (a.domains.trim()) who.push(L("li","- Knows deeply: "+a.domains.trim()+" — don't over-explain these."));
  who.push(L("li","- Coding experience: "+(a.experience==="new"?"new to this — teach the why as you go.":a.experience==="experienced"?"very experienced — concise and technical.":"comfortable — explain the non-obvious, skip the basics.")));
  sec("who",who);
  const how=[blank(), L("h2","## How we work")];
  how.push(L("li","- Tone: "+toneLine(a)));
  how.push(L("li","- Decisions: "+decisionLine(a)));
  how.push(L("li","- "+(a.brake==="yes"?"Be the brake — say so when something looks like a mistake, even unasked.":"Speak up about mistakes only when asked.")));
  if (a.docvsmem) how.push(L("li","- On a sparked idea, ask \"doc or memory?\""));
  sec("how",how);
  if (a.getToKnow) sec("learning",[
    blank(),
    L("h2","## Still learning  (blank = ask; filled = use)"),
    L("li","- Talks to me like:"),
    L("li","- Humor:"),
    L("li","- Wastes their time:"),
    L("li","- Their words / shorthand:"),
    L("li","- Hours & timezone:"),
    L("li","- Wants correction delivered:"),
  ]);
  sec("left",[
    blank(),
    L("h2","## Where we left off"),
    L("li","- "+today+": set up with Hello Claude. Nothing started yet."),
  ]);
  return S;
}

/**
 * Every file for one project, given the answers. The private pair is null when the user
 * keeps no notes — there is nowhere private to put them.
 * @param {Answers} a
 * @param { { today?: string } } [opts]  today as YYYY-MM-DD; injectable so tests are stable.
 */
export function generateDocs(a, opts={}){
  const contract=genContract(a,opts);
  return {
    contract,
    memory:  a.memory ? genMemory(a,opts) : null,
    primer:  a.memory ? genPrimer(a,opts) : null,
  };
}

/** Flatten a doc to the text that goes on disk. @param {Doc} doc */
export function docToText(doc){
  return doc.map(s=>s.lines.map(l=> l.c==="blank"?"":l.t).join("\n")).join("\n")+"\n";
}
