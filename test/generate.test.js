// @ts-check
import { test } from "node:test";
import assert from "node:assert/strict";
import { DEFAULTS, generateDocs, docToText } from "../src/generate.js";

const TODAY = "2026-09-16";
const answers = (over = {}) => ({ ...DEFAULTS, name: "Gene", role: "Streamer", domains: "Design; DR", ...over });
const text = (doc) => docToText(/** @type {any} */ (doc));
const ids = (doc) => /** @type {any[]} */ (doc).map((s) => s.id);

test("defaults produce all three documents", () => {
  const d = generateDocs(answers(), { today: TODAY });
  assert.ok(d.contract && d.memory && d.primer);
  assert.match(text(d.contract), /^# How we work — operating contract/);
  assert.match(text(d.contract), /personalized for Gene/);
  assert.match(text(d.memory), /Owner: Gene/);
  assert.match(text(d.primer), /^# ⛔ PRIVATE — do not commit/);
});

test("the person goes in the primer, never in the contract", () => {
  const d = generateDocs(answers(), { today: TODAY });
  assert.doesNotMatch(text(d.contract), /Streamer|Design; DR/);
  assert.match(text(d.primer), /Role: Streamer/);
  assert.match(text(d.primer), /Knows deeply: Design; DR/);
});

test("notes off: no private files, no memory footer, no get-to-know rule", () => {
  const d = generateDocs(answers({ memory: false }), { today: TODAY });
  assert.equal(d.memory, null);
  assert.equal(d.primer, null);
  assert.ok(!ids(d.contract).includes("memfoot"));
  assert.ok(!ids(d.contract).includes("getknow"));
});

test("get-to-know on: rule in the contract, blanks in the primer; off: neither", () => {
  const on = generateDocs(answers(), { today: TODAY });
  assert.ok(ids(on.contract).includes("getknow"));
  assert.match(text(on.contract), /ask ONE question that would fill a/);
  assert.match(text(on.primer), /## Still learning/);

  const off = generateDocs(answers({ getToKnow: false }), { today: TODAY });
  assert.ok(!ids(off.contract).includes("getknow"));
  assert.doesNotMatch(text(off.primer), /## Still learning/);
  assert.ok(off.primer, "primer still written when only the rule is off");
});

test("today is injectable and lands where dates rot", () => {
  const d = generateDocs(answers(), { today: "2001-01-01" });
  assert.match(text(d.contract), /Generated by Hello Claude · 2001-01-01/);
  assert.match(text(d.memory), /STATUS \(updated 2001-01-01\)/);
  assert.match(text(d.primer), /2001-01-01: set up with Hello Claude/);
});

test("docToText: blank lines are empty, file ends with one newline", () => {
  const t = text(generateDocs(answers(), { today: TODAY }).contract);
  assert.ok(t.endsWith("\n") && !t.endsWith("\n\n"));
  assert.ok(t.includes("\n\n"), "sections are separated by blank lines");
});

test("a nameless user still gets a coherent contract", () => {
  const d = generateDocs({ ...DEFAULTS }, { today: TODAY });
  assert.match(text(d.contract), /## The owner decides/);
  assert.match(text(d.primer), /## Who the owner is/);
});
